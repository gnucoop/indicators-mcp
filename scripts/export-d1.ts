#!/usr/bin/env bun
/**
 * Export indicators.db to a SQL file Cloudflare D1 can execute:
 *
 *   bun run export:d1                      # → dist/d1.sql
 *   bunx wrangler d1 execute indicators-mcp --remote --file dist/d1.sql
 *
 * `wrangler d1 export/import` skips FTS5 virtual tables, so this writes the
 * plain table, creates the FTS table and rebuilds it with INSERT ... SELECT.
 * No triggers on D1: the database there is read-only and replaced wholesale.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { parseArgs } from "node:util";
import { defaultDbPath, openDb } from "../src/db.ts";
import { SCHEMA_STATEMENTS } from "../src/schema.ts";
import type { UnifiedIndicator } from "../src/types.ts";

const { values } = parseArgs({
  args: Bun.argv.slice(2),
  options: {
    db: { type: "string" },
    out: { type: "string", default: "dist/d1.sql" },
  },
});

const D1_MAX_STATEMENT_BYTES = 100_000;

function lit(v: string | null): string {
  return v === null ? "NULL" : `'${v.replace(/'/g, "''")}'`;
}

const db = openDb(values.db ?? defaultDbPath(), { readonly: true });
const rows = db
  .query("SELECT id, source, title, sector, level, definition, methodology, url FROM indicators ORDER BY rowid")
  .all() as UnifiedIndicator[];
db.close();

const isTrigger = (s: string) => /^\s*CREATE TRIGGER/i.test(s);
const lines: string[] = [
  "-- Generated by scripts/export-d1.ts — replaces the whole catalog.",
  "DROP TABLE IF EXISTS indicators_fts;",
  "DROP TABLE IF EXISTS indicators;",
  ...SCHEMA_STATEMENTS.filter((s) => !isTrigger(s)).map((s) => `${s.replace(/\s+/g, " ").trim()};`),
];

let oversized = 0;
for (const r of rows) {
  const stmt =
    "INSERT INTO indicators (id, source, title, sector, level, definition, methodology, url) VALUES (" +
    [r.id, r.source, r.title, r.sector, r.level, r.definition, r.methodology, r.url].map(lit).join(", ") +
    ");";
  if (Buffer.byteLength(stmt) > D1_MAX_STATEMENT_BYTES) {
    oversized++;
    console.error(`Warning: ${r.id} exceeds D1's ${D1_MAX_STATEMENT_BYTES}-byte statement limit; trimming methodology.`);
    const trimmed = { ...r, methodology: `${(r.methodology ?? "").slice(0, 60_000)}\n\n… [truncated — see ${r.url}]` };
    lines.push(
      "INSERT INTO indicators (id, source, title, sector, level, definition, methodology, url) VALUES (" +
        [trimmed.id, trimmed.source, trimmed.title, trimmed.sector, trimmed.level, trimmed.definition, trimmed.methodology, trimmed.url]
          .map(lit)
          .join(", ") +
        ");",
    );
  } else {
    lines.push(stmt);
  }
}

lines.push(
  "INSERT INTO indicators_fts(rowid, id, title, sector, definition, methodology) " +
    "SELECT rowid, id, title, sector, definition, methodology FROM indicators;",
  "INSERT INTO indicators_fts(indicators_fts) VALUES('optimize');",
);

const out = resolve(values.out!);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${lines.join("\n")}\n`);
console.error(`Wrote ${rows.length} indicators to ${out} (${(Buffer.byteLength(lines.join("\n")) / 1024).toFixed(0)} KiB${oversized ? `, ${oversized} trimmed` : ""}).`);
